                            <i class="fas fa-search" style="color:#00a78e; margin-right:8px;"></i>Un proyecto de investigación en desarrollo
                        </h5>
                        <p class="dataset-description">
                            El desarrollo de esta iniciativa representa un proceso de investigación que avanza mediante la integración de tecnologías, la recopilación de información ambiental y el análisis de datos obtenidos directamente en las zonas costeras.
                            <br><br>
                            Actualmente, el proyecto contempla actividades de implementación, instrumentación, monitoreo y evaluación de los diferentes componentes que integran la propuesta. Cada etapa contribuye a fortalecer las capacidades técnicas y científicas necesarias para comprender mejor la relación entre la acumulación y descomposición del sargazo, las condiciones atmosféricas y la calidad del aire.
                            <br><br>
                            A medida que avance la investigación, se incorporarán nuevos registros, herramientas de análisis y resultados que permitirán ampliar el conocimiento sobre este fenómeno. De esta manera, buscamos construir progresivamente una plataforma de monitoreo ambiental que contribuya a generar información científica útil para las comunidades costeras y las autoridades.
                            <br><br>
                            Los avances y resultados que se generen serán compartidos mediante este espacio, bajo un enfoque de ciencia abierta, promoviendo el acceso al conocimiento y acercando la investigación científica a la sociedad.
                        </p>
                    </div>

