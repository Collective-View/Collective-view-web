                    <div id="descripcion" aria-label="Descripción del proyecto">
                        <h5 style="margin-top: 30px; margin-bottom: 15px; font-weight: 700; color: #0f172a;">
                            <i class="fas fa-wind" style="color:#00a78e; margin-right:8px;"></i>¿Por qué es importante monitorear la calidad del aire?
                        </h5>
                        <p class="dataset-description">
                            La llegada y acumulación de grandes cantidades de sargazo en las playas no solo representa un desafío ambiental y turístico. Cuando esta biomasa comienza a descomponerse, puede generar gases que modifican las condiciones del aire en las zonas costeras y cuya presencia requiere ser estudiada por sus posibles implicaciones para la salud y el bienestar de las personas.
                        </p>
                        <p class="dataset-description">
                            Por ello, es importante conocer qué sucede durante este proceso, cómo cambian las condiciones ambientales y de qué manera factores como la temperatura, la humedad y el viento pueden influir en la generación y dispersión de estos gases.
                        </p>
                        <p class="dataset-description">
                            Conocer la calidad del aire nos permite ir más allá de observar cuánto sargazo llega a nuestras playas: también nos ayuda a comprender qué ocurre durante su descomposición y cómo estos procesos interactúan con el entorno costero.
                        </p>


                        <h5 style="margin-top: 30px; margin-bottom: 15px; font-weight: 700; color: #0f172a;">
                            <i class="fas fa-wind" style="color:#00a78e; margin-right:8px;"></i>¿Cómo estamos estudiando este fenómeno?
                        </h5>
                        <p class="dataset-description">
                            Para contribuir a comprender este problema, estamos desarrollando el proyecto Sistema Integral de Alerta Sanitaria ante Emisiones de Gases por Descomposición de Sargazo en las Playas de Quintana Roo.
                        </p>
                        <p class="dataset-description">
                            Esta iniciativa busca desarrollar una plataforma de monitoreo ambiental que integre diferentes tecnologías y fuentes de información para estudiar las condiciones de la calidad del aire en playas con presencia de sargazo.
                        </p>
                        <p class="dataset-description">
                            Para ello, se contempla la utilización de sensores ambientales capaces de registrar variables como la concentración de gases, la temperatura, la humedad relativa y la velocidad y dirección del viento. Esta información se complementa con la captura de imágenes de las playas, que permite observar y analizar la presencia, distribución y estado de acumulación del sargazo.
                        </p>
                        <p class="dataset-description">
                            La integración de estas fuentes de información permitirá estudiar cómo se relacionan las condiciones ambientales, la acumulación de sargazo y la presencia de gases en el entorno. De esta manera, buscamos avanzar hacia una mejor comprensión de los procesos que ocurren en nuestras costas.
                        </p>
                    </div>

