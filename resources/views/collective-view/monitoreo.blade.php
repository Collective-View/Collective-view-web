                            <br><br>
                            La información recopilada permitirá avanzar en el desarrollo de indicadores que ayuden a interpretar las condiciones de la calidad del aire y establecer las bases científicas y tecnológicas para un futuro sistema de alerta sanitaria temprana.
                            <br><br>
