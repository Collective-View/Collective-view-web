                    <h5 style="margin-top: 40px; margin-bottom: 15px; font-weight: 700; color: #0f172a;">
                            ¿Qué buscamos lograr?
                        </h5>
                    <div class="spectral-box" id="objetivo-general" aria-labelledby="objetivo-general-heading" style="margin-top: 30px;">
                        <h5 id="objetivo-general-heading"><i class="fas fa-bullseye" style="color:#00a78e; margin-right:8px;"></i>Objetivo general</h5>
                        <p class="justify-text">
                            Desarrollar, implementar y evaluar una plataforma integral de monitoreo ambiental que permita registrar y analizar variables atmosféricas y visuales asociadas a la descomposición del sargazo en las playas de Quintana Roo. Mediante la integración de sensores ambientales, imágenes y herramientas de análisis de datos, buscamos comprender la relación entre la acumulación de biomasa, las condiciones atmosféricas y la presencia de gases potencialmente nocivos, estableciendo las bases científicas y tecnológicas para el desarrollo de un sistema de alerta sanitaria temprana.
                        </p>
                    </div>

                    <div id="lineas-trabajo" aria-labelledby="lineas-trabajo-heading">
                        <h5 id="lineas-trabajo-heading" style="margin-top: 40px; margin-bottom: 15px; font-weight: 700; color: #0f172a;">
                            <i class="fas fa-tasks" style="color:#00a78e; margin-right:8px;"></i>Líneas de trabajo
                        </h5>
                        <ul class="dataset-list">
                            <li class="justify-text">
                                <strong>Monitoreo de gases y condiciones atmosféricas:</strong> Implementar sistemas de medición para registrar concentraciones de gases, temperatura, humedad y condiciones del viento en zonas con acumulación de sargazo.
                            </li>
                            <li class="justify-text">
                                <strong>Análisis de imágenes de las playas:</strong> Desarrollar herramientas que permitan identificar y estimar la presencia, distribución y estado de acumulación del sargazo mediante fotografías y técnicas de análisis automatizado.
                            </li>
                            <li class="justify-text">
                                <strong>Adquisición y almacenamiento de datos:</strong> Integrar una infraestructura para recopilar, organizar y conservar los registros ambientales y visuales de manera continua y sincronizada.
                            </li>
                            <li class="justify-text">
                                <strong>Análisis espacial y temporal:</strong> Estudiar los cambios en las concentraciones de gases y su relación con la acumulación de sargazo y las condiciones ambientales.
                            </li>
                            <li class="justify-text">
                                <strong>Evaluación y validación en campo:</strong> Realizar pruebas, calibraciones y evaluaciones de los equipos y procedimientos de monitoreo para conocer su desempeño y confiabilidad.
                            </li>
                            <li class="justify-text">
                                <strong>Desarrollo de indicadores ambientales y sanitarios:</strong> Identificar patrones y definir indicadores preliminares que permitan establecer las bases para interpretar posibles condiciones de riesgo.
                            </li>
                            <li class="justify-text">
                                <strong>Generación y difusión del conocimiento:</strong> Elaborar productos científicos y técnicos, así como compartir los avances y resultados para facilitar su consulta y aprovechamiento por parte de la sociedad.
                            </li>
                        </ul>
                    </div>

